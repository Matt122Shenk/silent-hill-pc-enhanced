#!/usr/bin/env python3
"""Generate the RetroAchievements symbol table for builds without dlsym.

Pc_RaBuildMap (pc_retroachievements.c) turns the PSX addresses in
gamedata/ra/sym.*.txt into native addresses by looking each name up in the
running binary. Native builds ask dlsym; a wasm module has no symbol table to
ask at runtime, so the same lookup is answered from a table compiled in.

Data names are WEAK references: a name the PC build does not define (a static,
a PSX-only global) resolves to NULL at link time, which is exactly what a failed
dlsym returns, so the loader skips it the same way.

Code names cannot be weak data references (a type error at link time), and a
wasm function has no address in linear memory anyway. They still have to be
FOUND: the loader sizes every unsized symbol up to the next mapped one, and on
desktop the functions dlsym finds are what cap the last data symbol before a
code block. Leaving them out would let that symbol's span run across the whole
block. They map to one zeroed placeholder, so spans match desktop and a read
that lands in code yields 0 instead of machine code.
"""
import argparse
import re
from pathlib import Path

LINE = re.compile(r"^\s*([A-Za-z_]\w*)\s*=\s*0x([0-9A-Fa-f]+)\s*;")
SECTION = re.compile(r"//===\s*\.(\w+)\s+section")


def collect(paths):
    names, code = set(), set()
    for path in paths:
        section = "data"   # sym.extra.txt has no markers; it is all data
        for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
            m = SECTION.search(line)
            if m:
                section = m.group(1)
                continue
            m = LINE.match(line)
            if m and (int(m.group(2), 16) & 0xFF000000) == 0x80000000:
                (code if section == "text" else names).add(m.group(1))
    return sorted(names), sorted(code - names)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("symfiles", nargs="+")
    args = ap.parse_args()

    names, code = collect(args.symfiles)
    out = ["/* GENERATED by pc_port/tools/gen_ra_symtab.py - do not edit. */",
           "#include <stddef.h>",
           "#include <string.h>",
           ""]
    out += ["extern char %s __attribute__((weak));" % n for n in names]
    out += ["",
            "static char s_raCodeStub[0x10000];",
            "",
            "static const struct { const char* name; void* addr; } k_raSyms[] = {"]
    entries = [(n, "&%s" % n) for n in names] + [(n, "s_raCodeStub") for n in code]
    out += ['    { "%s", %s },' % e for e in sorted(entries)]
    out += ["};",
            "",
            "void* Pc_RaSymbolLookup(const char* name)",
            "{",
            "    size_t lo = 0, hi = sizeof(k_raSyms) / sizeof(k_raSyms[0]);",
            "",
            "    while (lo < hi)",
            "    {",
            "        size_t mid = (lo + hi) / 2;",
            "        int    c   = strcmp(name, k_raSyms[mid].name);",
            "",
            "        if (c == 0)",
            "            return k_raSyms[mid].addr;",
            "        if (c < 0)",
            "            hi = mid;",
            "        else",
            "            lo = mid + 1;",
            "    }",
            "    return NULL;",
            "}",
            ""]
    Path(args.output).write_text("\n".join(out), encoding="utf-8")
    print("[gen_ra_symtab] %d data + %d code symbols" % (len(names), len(code)))


if __name__ == "__main__":
    main()
