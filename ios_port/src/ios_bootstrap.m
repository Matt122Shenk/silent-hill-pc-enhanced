/*
 * ios_bootstrap.m — stage the port's own shipped assets into Documents.
 *
 * pc_port/assets/ (decal.png, the fonts, the language pack, UI sounds) is
 * copied next to the executable by CMake on desktop. Inside a signed .app that
 * tree is read-only, and the game resolves everything relative to the working
 * directory, which main_pc.c points at Documents. So the bundled copies are
 * staged across on first run.
 *
 * An app update has to reach those copies, or new code reads old data: see
 * Ios_StageBundledAssets for how a stale copy is told apart from one the
 * player edited. config.cfg is the exception and is only written when absent.
 *
 * This is the counterpart of BundledAssets.java on Android, which does the
 * same job out of the APK's AssetManager.
 *
 * The disc image is deliberately NOT part of this. Nothing copyrighted ships in
 * the bundle; the user supplies their own BIN/CUE through Files.app.
 */
#import <Foundation/Foundation.h>

/* SH_BUILD_GIT_HASH / SH_BUILD_STAMP: which build last compared its files
 * against this folder, so the comparison runs once per build rather than once
 * per launch. Generated by cmake/gen_build_info.cmake. */
#include "sh_build_info.h"

const char* Ios_DocumentsPath(void);
const char* Ios_BundleResourcePath(void);

/* Where the replaced copies go. Outside gamedata/, so no loader ever scans a
 * pack the player has been parted from. */
static NSString* const kIosReplacedDir = @"replaced_files";
/* One line per file, "<crc32 hex> <relative path>" -- the same format the
 * Android port's BundledAssets writes, so the two ports agree on what a
 * manifest is. */
static NSString* const kIosManifestRel = @"gamedata/.bundled_assets";
/* The build the comparison last ran against. A build that has already settled
 * only fills in missing files. */
static NSString* const kIosSettledKey = @"BundledAssetsSettledBuild";

/* CRC32, zlib polynomial. Thirty lines beats a link against libz, and matching
 * Android's CRC32 class is what keeps the manifest format shared. */
static unsigned int Crc32Of(NSData* data)
{
    static unsigned int table[256];
    static int          built = 0;
    const unsigned char* p    = (const unsigned char*)data.bytes;
    NSUInteger           n    = data.length;
    unsigned int         crc  = 0xFFFFFFFFu;
    NSUInteger           i;

    if (!built)
    {
        unsigned int k, c, b;

        for (k = 0; k < 256; k++)
        {
            c = k;
            for (b = 0; b < 8; b++)
            {
                c = (c & 1u) ? (0xEDB88320u ^ (c >> 1)) : (c >> 1);
            }
            table[k] = c;
        }
        built = 1;
    }

    for (i = 0; i < n; i++)
    {
        crc = table[(crc ^ p[i]) & 0xFFu] ^ (crc >> 8);
    }
    return crc ^ 0xFFFFFFFFu;
}

/* -1 when the file cannot be read, so the caller leaves it alone instead of
 * treating an I/O failure as "the copies differ". Nothing staged here is over
 * a megabyte, so these are whole-file reads. */
static long long Crc32OfFile(NSString* path)
{
    NSData* data = [NSData dataWithContentsOfFile:path];

    return (data == nil) ? -1 : (long long)Crc32Of(data);
}

/* Relative paths of every regular file under one staged item, which may be a
 * tree (gamedata) or a single file (gamecontrollerdb.txt). */
static void ListStaged(NSFileManager* fm, NSString* root, NSString* rel, NSMutableArray<NSString*>* out)
{
    NSString* full  = [root stringByAppendingPathComponent:rel];
    BOOL      isDir = NO;

    if (![fm fileExistsAtPath:full isDirectory:&isDir])
    {
        return;
    }
    if (!isDir)
    {
        [out addObject:rel];
        return;
    }
    for (NSString* child in [fm contentsOfDirectoryAtPath:full error:NULL])
    {
        ListStaged(fm, root, [rel stringByAppendingPathComponent:child], out);
    }
}

static BOOL CopyStaged(NSFileManager* fm, NSString* src, NSString* dst, NSString* rel)
{
    NSError* err = nil;

    [fm createDirectoryAtPath:[dst stringByDeletingLastPathComponent]
  withIntermediateDirectories:YES
                   attributes:nil
                        error:&err];
    if (![fm copyItemAtPath:src toPath:dst error:&err])
    {
        NSLog(@"[SH] could not stage %@: %@", rel, err.localizedDescription);
        return NO;
    }
    return YES;
}

static NSMutableDictionary<NSString*, NSNumber*>* ReadManifest(NSString* docs)
{
    NSMutableDictionary<NSString*, NSNumber*>* m = [NSMutableDictionary dictionary];
    NSString* text = [NSString stringWithContentsOfFile:
                                   [docs stringByAppendingPathComponent:kIosManifestRel]
                                               encoding:NSUTF8StringEncoding
                                                  error:NULL];

    for (NSString* line in [(text ?: @"") componentsSeparatedByString:@"\n"])
    {
        NSRange sp = [line rangeOfString:@" "];
        unsigned crc = 0;

        if (sp.location == NSNotFound || sp.location == 0)
        {
            continue;
        }
        if (![[NSScanner scannerWithString:[line substringToIndex:sp.location]] scanHexInt:&crc])
        {
            continue;
        }
        m[[line substringFromIndex:sp.location + 1]] = @(crc);
    }
    return m;
}

static void WriteManifest(NSFileManager* fm, NSString* docs, NSDictionary<NSString*, NSNumber*>* m)
{
    NSString*       path = [docs stringByAppendingPathComponent:kIosManifestRel];
    NSMutableString* out = [NSMutableString string];

    for (NSString* rel in m)
    {
        [out appendFormat:@"%x %@\n", (unsigned)m[rel].unsignedIntValue, rel];
    }
    [fm createDirectoryAtPath:[path stringByDeletingLastPathComponent]
  withIntermediateDirectories:YES
                   attributes:nil
                        error:NULL];
    if (![out writeToFile:path atomically:YES encoding:NSUTF8StringEncoding error:NULL])
    {
        NSLog(@"[SH] could not write %@", kIosManifestRel);
    }
}

/* Moves the copy on disk aside, then writes the bundle's. Documents is the
 * folder Files.app shows, so a player who wanted what was there can fetch it
 * back without a computer -- which is why this port replaces where Android
 * asks: the note below is reachable, and Android's data root is not from
 * Android 11 on. */
static BOOL ReplaceStaged(NSFileManager* fm, NSString* bundle, NSString* docs, NSString* rel)
{
    NSString* src = [bundle stringByAppendingPathComponent:rel];
    NSString* dst = [docs stringByAppendingPathComponent:rel];
    NSString* bak = [[docs stringByAppendingPathComponent:kIosReplacedDir]
                        stringByAppendingPathComponent:rel];
    NSError*  err = nil;

    [fm createDirectoryAtPath:[bak stringByDeletingLastPathComponent]
  withIntermediateDirectories:YES
                   attributes:nil
                        error:&err];
    if ([fm fileExistsAtPath:bak])
    {
        [fm removeItemAtPath:bak error:NULL];
    }
    if (![fm moveItemAtPath:dst toPath:bak error:&err])
    {
        NSLog(@"[SH] could not keep a copy of %@: %@", rel, err.localizedDescription);
        if (![fm removeItemAtPath:dst error:&err])
        {
            return NO;
        }
    }
    return CopyStaged(fm, src, dst, rel);
}

static void WriteReplacedNote(NSString* docs, NSArray<NSString*>* replaced)
{
    NSString*        dir  = [docs stringByAppendingPathComponent:kIosReplacedDir];
    NSMutableString* text = [NSMutableString stringWithString:
        @"The app update below shipped newer copies of these files, and the\n"
         "copies that were here are the ones kept in this folder.\n"
         "\n"
         "Old copies are not harmless: the text and the font art are written\n"
         "against each other, so an old language pack meeting new font code\n"
         "draws the wrong letters.\n"
         "\n"
         "To put one of yours back, copy it from here over the file of the same\n"
         "name under gamedata/. It is then treated as yours and no later update\n"
         "replaces it.\n"
         "\n"];

    [text appendFormat:@"Replaced by build %s:\n", SH_BUILD_GIT_HASH];
    for (NSString* rel in replaced)
    {
        [text appendFormat:@"  %@\n", rel];
    }

    if (![text writeToFile:[dir stringByAppendingPathComponent:@"README.txt"]
               atomically:YES
                 encoding:NSUTF8StringEncoding
                    error:NULL])
    {
        NSLog(@"[SH] could not write the replaced-files note");
    }
}

/* Factory reset for the settings. There is no full config writer in the port
 * (only per-key saves), but iOS ships a pristine config.cfg inside the signed,
 * read-only bundle, so restoring it is just a copy over the staged one --
 * genuinely the file the app was built with, not a guess at what the defaults
 * were. Returns 1 on success.
 *
 * The caller reloads afterwards; rows the menu marks as needing a restart still
 * need one, exactly as they would after editing the file by hand. */
int Ios_RestoreDefaultConfig(void)
{
    int ok = 0;

    @autoreleasepool
    {
        const char* docs   = Ios_DocumentsPath();
        const char* bundle = Ios_BundleResourcePath();
        if (docs == NULL || bundle == NULL)
        {
            return 0;
        }

        NSFileManager* fm  = [NSFileManager defaultManager];
        NSString*      src = [[fm stringWithFileSystemRepresentation:bundle length:strlen(bundle)]
                                stringByAppendingPathComponent:@"config.cfg"];
        NSString*      dst = [[fm stringWithFileSystemRepresentation:docs length:strlen(docs)]
                                stringByAppendingPathComponent:@"config.cfg"];

        if (![fm fileExistsAtPath:src])
        {
            NSLog(@"[SH] no bundled config.cfg to restore from");
            return 0;
        }

        NSError* err = nil;
        if ([fm fileExistsAtPath:dst])
        {
            [fm removeItemAtPath:dst error:&err];
        }
        ok = [fm copyItemAtPath:src toPath:dst error:&err] ? 1 : 0;
        if (!ok)
        {
            NSLog(@"[SH] config restore failed: %@", err.localizedDescription);
        }
    }

    return ok;
}

/* The port's own shipped files -- fonts, language packs, title art, UI sounds,
 * the pad database -- kept in step with the bundle.
 *
 * They used to be written only when missing, so an app update never reached a
 * player who already had them: the new font code read an old pl.lang and
 * Polish letters drew as the wrong glyphs. Found and fixed on Android first;
 * the cause is the same here, because the staging was the same.
 *
 * The manifest records what this code installed, which is what separates a
 * stale copy from the player's own:
 *   - the copy on disk is the one we installed and the bundle has changed
 *     since: stale, so it is replaced;
 *   - the copy on disk is something else, and we installed the version the
 *     bundle now carries: the player edited it, and it is left alone;
 *   - there is no record at all (an install from before the manifest): the
 *     bundle is newer, so it is replaced.
 * Everything replaced is kept in replaced_files/ with a note, which on this
 * port is a folder the player can open in Files.app.
 *
 * config.cfg is deliberately not part of this -- it holds the player's
 * settings, so it is still only written when absent.
 */
void Ios_StageBundledAssets(void)
{
    @autoreleasepool
    {
        const char* docsC   = Ios_DocumentsPath();
        const char* bundleC = Ios_BundleResourcePath();

        if (docsC == NULL || bundleC == NULL)
        {
            return;
        }

        NSFileManager* fm     = [NSFileManager defaultManager];
        NSString*      docs   = [fm stringWithFileSystemRepresentation:docsC length:strlen(docsC)];
        NSString*      bundle = [fm stringWithFileSystemRepresentation:bundleC length:strlen(bundleC)];
        /* gamecontrollerdb.txt is a loose file at the bundle root rather than
         * part of a tree, and PsyCross opens it by that name relative to the
         * working directory -- so until it was staged, a pad SDL's built-in
         * list does not already know could not be mapped at all. */
        NSArray<NSString*>*        items = @[ @"gamedata", @"licenses", @"gamecontrollerdb.txt" ];
        NSMutableArray<NSString*>* files = [NSMutableArray array];
        NSUserDefaults*            prefs = [NSUserDefaults standardUserDefaults];
        NSString*                  stamp = [NSString stringWithFormat:@"%s %s:%@",
                                                SH_BUILD_GIT_HASH, SH_BUILD_STAMP, docs];

        for (NSString* item in items)
        {
            ListStaged(fm, bundle, item, files);
        }

        if ([stamp isEqualToString:[prefs stringForKey:kIosSettledKey]])
        {
            /* This build has already been compared against this folder, so
             * there is nothing to read: fill in anything missing and go. */
            for (NSString* rel in files)
            {
                NSString* dst = [docs stringByAppendingPathComponent:rel];

                if (![fm fileExistsAtPath:dst])
                {
                    CopyStaged(fm, [bundle stringByAppendingPathComponent:rel], dst, rel);
                }
            }
        }
        else
        {
            NSMutableDictionary<NSString*, NSNumber*>* manifest = ReadManifest(docs);
            NSMutableArray<NSString*>*                replaced = [NSMutableArray array];
            NSMutableArray<NSString*>*                kept     = [NSMutableArray array];

            for (NSString* rel in files)
            {
                NSString* src = [bundle stringByAppendingPathComponent:rel];
                NSString* dst = [docs stringByAppendingPathComponent:rel];
                long long bundled;
                long long disk;
                NSNumber* installed;

                bundled = Crc32OfFile(src);
                if (bundled < 0)
                {
                    continue;
                }

                if (![fm fileExistsAtPath:dst])
                {
                    if (CopyStaged(fm, src, dst, rel))
                    {
                        manifest[rel] = @((unsigned int)bundled);
                    }
                    continue;
                }

                disk = Crc32OfFile(dst);
                /* An unreadable file is not a changed one: say nothing about it
                 * rather than replace what might be fine. */
                if (disk < 0)
                {
                    continue;
                }
                if (disk == bundled)
                {
                    manifest[rel] = @((unsigned int)bundled);
                    continue;
                }

                installed = manifest[rel];
                if (installed != nil && (long long)installed.unsignedIntValue != disk)
                {
                    [kept addObject:rel];
                    continue;
                }
                if (ReplaceStaged(fm, bundle, docs, rel))
                {
                    manifest[rel] = @((unsigned int)bundled);
                    [replaced addObject:rel];
                }
            }

            WriteManifest(fm, docs, manifest);
            if (replaced.count != 0)
            {
                NSLog(@"[SH] updated %lu bundled file(s): %@", (unsigned long)replaced.count,
                      [replaced componentsJoinedByString:@", "]);
                WriteReplacedNote(docs, replaced);
            }
            if (kept.count != 0)
            {
                NSLog(@"[SH] left your own copies alone: %@", [kept componentsJoinedByString:@", "]);
            }
            [prefs setObject:stamp forKey:kIosSettledKey];
        }

        if (![fm fileExistsAtPath:[docs stringByAppendingPathComponent:@"config.cfg"]])
        {
            CopyStaged(fm, [bundle stringByAppendingPathComponent:@"config.cfg"],
                       [docs stringByAppendingPathComponent:@"config.cfg"], @"config.cfg");
        }
    }
}

/* A PSX memory card is a file, and nothing in the port ever creates one:
 * MemCardFormat is an unimplemented stub, and MemCardExist just fopen()s
 * "<chan>.MCD" relative to the working directory. With no card on disk the
 * save screen sits on "checking the memory card" forever, because the check it
 * is waiting on can never succeed.
 *
 * So lay down a blank FORMATTED card on first run, the way a console ships with
 * one in the slot. 128 KB = 1024 frames x 128 bytes, and "formatted" is the
 * part that matters: frame 0 carries the "MC" magic and its checksum, frames
 * 1..15 are the directory and each must say FREE (0xA0), and the data frames
 * are 0xFF. A card of zeros with only the magic passes for a card and then
 * cannot hold anything -- a zeroed entry is neither free nor used, so the
 * allocator finds no slot and every save fails while the card reads as empty,
 * which sat the save screen on "Now checking MEMORY CARD" (reported
 * 2026-09-23). This is the same image PsyCross writes in mc_format_buffer,
 * which also repairs a zeroed card left by the old version of this function.
 *
 * Never overwrites an existing card -- that would erase the player's saves. */
void Ios_EnsureMemoryCard(void)
{
    @autoreleasepool
    {
        const char* docs = Ios_DocumentsPath();
        if (docs == NULL)
        {
            return;
        }

        NSFileManager* fm = [NSFileManager defaultManager];
        NSString*      dir = [fm stringWithFileSystemRepresentation:docs length:strlen(docs)];

        for (int chan = 0; chan < 2; chan++)
        {
            NSString* path = [dir stringByAppendingPathComponent:
                                 [NSString stringWithFormat:@"%d.MCD", chan]];

            if ([fm fileExistsAtPath:path])
            {
                continue;
            }

            NSMutableData* card = [NSMutableData dataWithLength:128 * 1024];
            unsigned char* p    = (unsigned char*)card.mutableBytes;

            /* Data frames first, then the header and directory over the top. */
            memset(p, 0xFF, 128 * 1024);
            memset(p, 0, 128);
            p[0] = 'M';
            p[1] = 'C';
            {
                unsigned char xorck = 0;
                for (int i = 0; i < 127; i++)
                {
                    xorck ^= p[i];
                }
                p[127] = xorck;
            }
            for (int e = 1; e <= 15; e++)
            {
                unsigned char* dir = p + (e * 128);

                memset(dir, 0, 128);
                dir[0] = 0xA0; /* free */
                {
                    unsigned char xorck = 0;
                    for (int i = 0; i < 127; i++)
                    {
                        xorck ^= dir[i];
                    }
                    dir[127] = xorck;
                }
            }

            if (![card writeToFile:path atomically:YES])
            {
                NSLog(@"[SH] could not create %@", path.lastPathComponent);
            }
        }
    }
}

/* Create the mod folders, empty, on first run.
 *
 * Everything the loose-file loader reads is a relative path under gamedata/,
 * and the chdir to Documents already makes those resolve somewhere the user
 * can reach. The gap is purely discoverability: Files.app shows what exists,
 * so a folder nobody created is a folder nobody finds, and the player has no
 * launcher and no documentation on the device telling them the names to type.
 *
 * Only the two roots and a note. The per-folder layout underneath (ITEM, SND,
 * XA and the rest) mirrors the disc's own folder names, which is what the note
 * explains, and guessing a full tree here would just create empty folders for
 * channels most players never touch.
 *
 * Never overwrites: a player who has already put mods in keeps what they have,
 * and an edited note stays edited. */
void Ios_EnsureModFolders(void)
{
    @autoreleasepool
    {
        const char* docs = Ios_DocumentsPath();
        if (docs == NULL)
        {
            return;
        }

        NSFileManager* fm   = [NSFileManager defaultManager];
        NSString*      root = [fm stringWithFileSystemRepresentation:docs length:strlen(docs)];
        NSString*      load = [root stringByAppendingPathComponent:@"gamedata/load"];
        NSString*      tex  = [root stringByAppendingPathComponent:@"gamedata/texturemods"];
        NSString*      note = [load stringByAppendingPathComponent:@"README.txt"];

        for (NSString* dir in @[ load, tex ])
        {
            NSError* err = nil;
            if (![fm createDirectoryAtPath:dir
               withIntermediateDirectories:YES
                                attributes:nil
                                     error:&err])
            {
                NSLog(@"[SH] could not create %@: %@", dir, err.localizedDescription);
            }
        }

        if (![fm fileExistsAtPath:note])
        {
            NSString* text =
                @"Manually installed mods go here.\n"
                 "\n"
                 "Mods are on by default. Options > Graphics > Load Mods turns\n"
                 "them off. Restart the game after adding or removing files.\n"
                 "\n"
                 "gamedata/load/<FOLDER>/<NAME>\n"
                 "  <FOLDER> and <NAME> are the disc's own folder and file names,\n"
                 "  so a replacement sits at the path the original came from,\n"
                 "  e.g. gamedata/load/CHARA/HERO.TIM. Case does not matter.\n"
                 "\n"
                 "Textures:  <NAME>.png or <NAME>.dds beside it (HERO.TIM.png or\n"
                 "           HERO.png), or a replacement .TIM with the same name\n"
                 "Models:    replacement .TMD / .ILM / .IPD; .glb for items\n"
                 "Sounds:    SND/<BANK>.VAB, or one sound as SND/<BANK>.001.wav\n"
                 "Voices:    XA/xa_0001.wav, or XA/msg_<KEY>.wav for a text box\n"
                 "Text:      text_overrides.txt, or text_overrides/<name>.txt\n"
                 "\n"
                 "gamedata/texturemods/ takes DuckStation-format texture packs,\n"
                 "as a folder or a .zip. Always on, no switch needed.\n";

            NSError* err = nil;
            if (![text writeToFile:note atomically:YES
                          encoding:NSUTF8StringEncoding error:&err])
            {
                NSLog(@"[SH] could not write the mod note: %@", err.localizedDescription);
            }
        }
    }
}
